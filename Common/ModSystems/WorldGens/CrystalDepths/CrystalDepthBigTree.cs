		public int Variant { get; private set; }

		public int Height => _targetTiles.GetLength(0);
		public int Width => _targetTiles.GetLength(1);

		private byte[,] _targetTiles;

		public CrystalDepthBigTree(int variant)
		{
			Variant = variant;

			switch (Variant)
			{
				case 0:
					_targetTiles = _variant0;
					break;
				case 1:
					_targetTiles = _variant1;
					break;
			}
		}
		public void Place(int pointX, int pointY)
		{
			var treeChestX = 0;
			var treeChestY = 0;

			for (int x = 0; x < 28; x++)
			{
				for (int y = 0; y < 32; y++)
				{
					Tile tile = Framing.GetTileSafely(pointX + x, pointY - y);
					var globalX = pointX + x;
					var globalY = pointY - y;
					PlaceBlock(_targetTiles[y, x], globalX, globalY);

					if (Variant == 0)
					{
						treeChestX = 12;
						treeChestY = 7;
					}
					else
					{
						treeChestX = 12;
						treeChestY = 5;
					}
				}
			}
			WorldGen.PlaceChest(pointX + treeChestX, pointY - treeChestY, (ushort)TileType<DeepChest>(), false, 1);

		}

		private void PlaceBlock(byte tree, int globalX, int globalY)
		{
			Tile tile = Framing.GetTileSafely(globalX, globalY);
			switch (tree)
			{
				case 0:
					break;
				case 1:
					tile.TileType = DepthsTiles.Tree;
					tile.HasTile = true;
					WorldGen.SlopeTile(globalX, globalY, 0);
					break;
				case 2:
					tile.TileType = DepthsTiles.Leaf;
					tile.HasTile = true;
					WorldGen.SlopeTile(globalX, globalY, 0);
					break;
				case 3:
					WorldGen.KillTile(globalX, globalY);
					WorldGen.KillTile(globalX, globalY);
					break;
			}
		}
		

		
